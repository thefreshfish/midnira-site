"""Draws the figures at the top of the two practice pages.

  ai-operations.html        routes: the night's mail, carried to a sign-off line
  penetration-testing.html  scopemap: the signed scope as a map of 10.20.0.0/24

Run from the site folder:

  python3 tools/figures.py

Each figure is rewritten between its <!-- name:start --> and <!-- name:end -->
comments. Colors, type and motion come from classes in site.css. The
interactions are in site.js: approvals in the morning queue turn a route amber
and file it (data-doc, data-folder), and a check in the scope gate rings the
cell it names (data-mark). Keep those values in step with the queue and the
gate on the same page.
"""
import pathlib

SITE = pathlib.Path(__file__).resolve().parent.parent
INDENT = "          "


def put(page, name, svg):
    path = SITE / page
    html = path.read_text(encoding="utf-8")
    start = "<!-- %s:start (generated by tools/figures.py) -->" % name
    end = "<!-- %s:end -->" % name
    a, b = html.find(start), html.find(end)
    if a < 0 or b < 0:
        raise SystemExit("%s block not found in %s" % (name, page))
    body = "\n".join(INDENT + line if line else line for line in svg.strip("\n").split("\n"))
    html = html[:a + len(start)] + "\n" + body + "\n" + INDENT + html[b:]
    path.write_text(html, encoding="utf-8")


# ---- routes ----------------------------------------------------------------
# Folder names as the queue writes them (the <option> text), and how the
# figure labels them.
FOLDERS = [
    ("Matter 1874 › Medical records", "1874 › Medical records"),
    ("Matter 1874 › Correspondence", "1874 › Correspondence"),
    ("Matter 1847 › Correspondence", "1847 › Correspondence"),
    ("Matter 2291 › Court notices", "2291 › Court notices"),
    ("Matter 2291 › Pleadings", "2291 › Pleadings"),
    ("Unmatched mail", "Unmatched mail"),
]
DEST_Y = [64, 136, 208, 280, 352, 424]
GATE_X = 330
DEST_X = 400

# (data-doc as in the queue, label, start point, y at the gate, proposed folder, other choices)
DOCS = [
    ("the medical records", "Medical records", (88, 122), 110, 0, [1, 5]),
    ("the cover letter", "Cover letter", (88, 152), 200, 2, [1, 5]),
    ("the notice of hearing", "Notice of hearing", (96, 326), 330, 3, [4, 5]),
]


def hop(y0, y1):
    """The short curve from the sign-off line to a folder."""
    return "M %d %d C %d %d %d %d %d %d" % (GATE_X, y0, GATE_X + 38, y0, DEST_X - 34, y1, DEST_X - 6, y1)


def routes():
    out = []
    out.append('<svg class="figure routes" viewBox="0 0 640 460" role="img" aria-labelledby="routes-title routes-desc">')
    out.append('  <title id="routes-title">The night\'s mail, routed to a sign-off line</title>')
    out.append('  <desc id="routes-desc">A fax at 11:42 PM is split into medical records and a cover letter, and an email at 1:07 AM '
               'brings a notice of hearing. The agent proposes a folder for each document, and each proposal waits at the '
               'sign-off line until a person approves it.</desc>')
    # sources
    out.append('  <g class="source">')
    out.append('    <rect class="sheet" x="20" y="96" width="62" height="80" rx="2"/>')
    for i, w in enumerate([40, 34, 40, 22]):
        out.append('    <line class="sheet-line" x1="30" y1="%d" x2="%d" y2="%d"/>' % (112 + i * 14, 30 + w, 112 + i * 14))
    out.append('    <text class="src-name" x="20" y="202">Fax, 14 pages</text>')
    out.append('    <text class="src-time" x="20" y="224">11:42 PM</text>')
    out.append('  </g>')
    out.append('  <g class="source">')
    out.append('    <rect class="sheet" x="20" y="300" width="72" height="50" rx="3"/>')
    out.append('    <polyline class="sheet-line" points="22,302 56,328 90,302"/>')
    out.append('    <text class="src-name" x="20" y="376">Email</text>')
    out.append('    <text class="src-time" x="20" y="398">1:07 AM</text>')
    out.append('  </g>')
    # the sign-off line
    out.append('  <line class="gate-line" x1="%d" y1="48" x2="%d" y2="444"/>' % (GATE_X, GATE_X))
    out.append('  <text class="gate-name" x="%d" y="32">Sign-off</text>' % GATE_X)
    # folders
    for (folder, label), y in zip(FOLDERS, DEST_Y):
        out.append('  <g class="dest" data-folder="%s">' % folder)
        out.append('    <path class="folder-glyph" d="M %d %d h 7 l 3 3 h 10 v 13 h -20 z"/>' % (DEST_X, y - 11))
        out.append('    <text class="dest-name" x="%d" y="%d">%s</text>' % (DEST_X + 28, y + 6, label))
        out.append('  </g>')
    # documents: the agent's route, the proposal, and every way a person could file it
    for i, (doc, label, (x0, y0), yg, proposed, others) in enumerate(DOCS):
        out.append('  <g class="doc" data-i="%d">' % i)
        out.append('    <path class="route" data-i="%d" pathLength="1" d="M %d %d C %d %d %d %d %d %d"/>'
                   % (i, x0, y0, 150, y0, 170, yg, GATE_X, yg))
        out.append('    <path class="proposal" data-i="%d" data-doc="%s" d="%s"/>' % (i, doc, hop(yg, DEST_Y[proposed])))
        for f in [proposed] + others:
            out.append('    <path class="filed" pathLength="1" data-doc="%s" data-folder="%s" d="%s"/>'
                       % (doc, FOLDERS[f][0], hop(yg, DEST_Y[f])))
        out.append('    <text class="doc-name" data-i="%d" x="%d" y="%d">%s</text>' % (i, GATE_X - 12, yg - 20, label))
        out.append('    <circle class="wait" data-i="%d" data-doc="%s" cx="%d" cy="%d" r="7"/>' % (i, doc, GATE_X, yg))
        out.append('  </g>')
    out.append('</svg>')
    return "\n".join(out)


# ---- scope map ---------------------------------------------------------------
LEFT, TOP, PITCH, CELL = 64, 112, 30, 26
HOSTS = [1, 2, 10, 11, 14, 20, 21, 33, 40, 64, 65, 80, 100, 101, 128, 129, 150, 200, 201, 250, 254]
EXCLUDED = 53


def scopemap():
    found = len(HOSTS) + 2
    out = []
    out.append('<svg class="figure scopemap" viewBox="0 0 600 684" role="img" aria-labelledby="scope-title scope-desc">')
    out.append('  <title id="scope-title">The signed scope, as a map</title>')
    out.append('  <desc id="scope-desc">Two hostnames and the 256 addresses of 10.20.0.0/24 are in scope. The agent checked '
               'each one and found %d hosts. 10.20.0.53, the production database, is excluded by name and was never '
               'contacted, and nothing in 10.20.1.0/24 was touched. One finding, on api.example.com, was reproduced by the '
               'operator.</desc>' % found)
    # hostnames
    for x, name in [(LEFT, "app.example.com"), (LEFT + 248, "api.example.com")]:
        out.append('  <g class="host" data-r="0">')
        out.append('    <rect class="host-cell" data-mark="%s" x="%d" y="16" width="228" height="48" rx="6"/>' % (name, x))
        out.append('    <text class="host-name" x="%d" y="46">%s</text>' % (x + 114, name))
        if name.startswith("api"):
            out.append('    <circle class="finding" cx="%d" cy="16" r="8"/>' % (x + 228))
        out.append('  </g>')
    # the in-scope network
    out.append('  <text class="net-name" x="%d" y="98">10.20.0.0/24</text>' % LEFT)
    for r in range(16):
        y = TOP + r * PITCH
        out.append('  <g class="row" data-r="%d">' % (r + 1))
        out.append('    <text class="row-label" x="%d" y="%d">.%d</text>' % (LEFT - 10, y + 18, r * 16))
        for c in range(16):
            n, x = r * 16 + c, LEFT + c * PITCH
            if n == EXCLUDED:
                out.append('    <rect class="cell is-excluded" data-mark="10.20.0.%d" x="%d" y="%d" width="%d" height="%d" rx="4"/>'
                           % (n, x, y, CELL, CELL))
                out.append('    <path class="x-mark" d="M %d %d l 12 12 m 0 -12 l -12 12"/>' % (x + 7, y + 7))
            else:
                kind = "cell is-host" if n in HOSTS else "cell"
                out.append('    <rect class="%s" data-mark="10.20.0.%d" x="%d" y="%d" width="%d" height="%d" rx="4"/>'
                           % (kind, n, x, y, CELL, CELL))
        out.append('  </g>')
    # the next network over, which the scope does not name
    y = TOP + 16 * PITCH + 46
    out.append('  <text class="net-name is-outside" x="%d" y="%d">10.20.1.0/24, outside the scope</text>' % (LEFT, y - 12))
    out.append('  <g class="row" data-r="17">')
    for c in range(16):
        out.append('    <rect class="cell is-outside" data-mark="10.20.1.%d" x="%d" y="%d" width="%d" height="%d" rx="4"/>'
                   % (c, LEFT + c * PITCH, y, CELL, CELL))
    out.append('  </g>')
    out.append('</svg>')
    return "\n".join(out)


if __name__ == "__main__":
    put("ai-operations.html", "routes", routes())
    put("penetration-testing.html", "scopemap", scopemap())
    print("figures: drew routes and scopemap")
